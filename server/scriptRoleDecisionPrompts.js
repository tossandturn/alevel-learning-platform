export function applyDecisionPrompts(game){
 for(const role of game.roles)for(const mission of role.missions||[]){
  const lines=prompts[role.id]?.[mission.stage]
  if(!lines||lines.length!==mission.options.length)throw Error('Missing role-specific decision prompts')
  for(const [index,option]of mission.options.entries()){
   option.followup=lines[index]
   delete option.consequence
  }
 }
 return game
}
