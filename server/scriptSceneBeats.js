function definition(game,stage){
 if(!game||game.version<2||!Number.isInteger(stage)||stage<0||stage>2)return null
 const book=Object.hasOwn(books,game.id)?books[game.id]:null
 if(!book||book.edition&&book.edition!==game.contentEdition)return null
 if(Object.entries(book.names).some(([id,name])=>!game.roles.some(r=>r.id===id&&r.name===name)))return null
 return book.scenes[stage]||null
}
export function scriptStageScene(game,stage,aiRoleIds=[]){
 const authored=definition(game,stage);if(!authored)return null
 const wanted=new Set(aiRoleIds),order=game.roles.map(r=>r.id).filter(id=>wanted.has(id)),lines=[]
 for(const actor of order){
  const beat=authored.cast[actor],previous=lines.at(-1)?.actor||null,text=previous?beat.after[previous]:beat.open
  if(typeof text!=='string'||!text.trim())throw Error('Missing authored scene branch')
  const parts=[...(beat.narration?[{kind:'narration',text:beat.narration}]:[]),{kind:'speech',text}]
  lines.push({actor,respondsTo:previous,parts})
 }
 return {version:SCRIPT_SCENE_VERSION,key:`${game.id}:${game.contentEdition||game.version}:${stage}`,narration:authored.narration,lines}
}
export function scriptStandaloneEntrance(game,role,stage){return game?.roles?.some(r=>r.id===role?.id&&r.name===role?.name)?definition(game,stage)?.cast[role.id]?.open||'':''}
